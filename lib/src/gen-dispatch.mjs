// Generates the dispatch cases of lib/src/mars.c: case labels on the
// instruction word (op byte | A mode << 8 | B mode << 11), each calling
// exec_ins() with a constant word, so that clang compiles a copy of the
// instruction without mode or opcode branches. Words without a case run
// the generic code.
//
//   node lib/src/gen-dispatch.mjs [--hot | --full | --partial] [-o file]
//   node lib/src/gen-dispatch.mjs --rank [--top 32] <count files...>
//
//   --hot      (default) one case per entry of HOT below: what
//              wasm/build.sh uses, written to lib/src/dispatch.h. The cases
//              after the first 16 are inside #ifndef M42_DISPATCH_16, which
//              lib/src/platform.h defines for MSVC
//   --full     one case per combination of opcode, modifier, A mode and B
//              mode (19 * 7 * 8 * 8 = 8512); slower and much larger, see
//              docs/performance-log.md
//   --partial  one case per opcode, modifier and B mode (1064), the A mode
//              stays a run-time branch; also slower
//   --rank     ranks instruction words by execution count. A count file has
//              lines "<word> <count>", as printed by bench-native.c built
//              with -DCOUNT_INS; every file gets the same weight. Prints a
//              HOT list.
//
// The output is deterministic: wasm/build.sh regenerates dispatch.h
// and the committed file must not change.

import { readFileSync, writeFileSync } from 'node:fs';

const OPS = ['mov', 'add', 'sub', 'mul', 'div', 'mod', 'jmz', 'jmn', 'djn', 'cmp', 'slt', 'spl', 'dat', 'jmp', 'seq', 'sne', 'nop', 'ldp', 'stp'];
const MODS = ['a', 'b', 'ab', 'ba', 'f', 'x', 'i'];
const MODES = '#$@<>*{}';

// The most executed instruction words, measured over the t20 and t80
// tournaments, 400 random corpus pairs and the bench (each weighted
// equally; --rank, docs/performance-log.md). Counts with and without early
// ties give this same list (#23). 32 cases were faster in WebAssembly than
// 16, 24, 40, 48 and 64.
const HOT = [
  'spl.b $ <', 'mov.i $ <', 'spl.b $ $', 'mov.i $ $', 'jmp.b $ $', 'jmp.b $ <', 'dat.f < <', 'add.ab # $',
  'dat.f $ $', 'dat.f # #', 'mov.i $ @', 'djn.b $ <', 'djn.b $ $', 'mov.i @ <', 'mov.i < <', 'djn.b $ #',
  'spl.b @ $', 'cmp.i $ $', 'jmn.b $ $', 'add.f $ $', 'spl.b $ #', 'mov.ab # $', 'sub.ab # $', 'cmp.i < <',
  'jmp.b $ #', 'dat.f < #', 'sub.f $ $', 'jmz.b $ @', 'slt.ab # $', 'jmz.b $ $', 'jmp.b @ $', 'cmp.ab # $',
];

const word = (op, mod, am, bm) => (op << 3) | mod | (am << 8) | (bm << 11);
const name = (w) => `${OPS[(w & 0xff) >> 3]}.${MODS[w & 7]} ${MODES[(w >> 8) & 7]} ${MODES[w >> 11]}`;

function parse(text) {
  const m = /^([a-z]+)\.([a-z]+) (\S) (\S)$/.exec(text);
  const op = m && OPS.indexOf(m[1]);
  const mod = m && MODS.indexOf(m[2]);
  const am = m && MODES.indexOf(m[3]);
  const bm = m && MODES.indexOf(m[4]);
  if (!m || op < 0 || mod < 0 || am < 0 || bm < 0) throw new Error(`bad HOT entry '${text}'`);
  return word(op, mod, am, bm);
}

const argv = process.argv.slice(2);
const take = (flag) => { const i = argv.indexOf(flag); return i >= 0 ? argv.splice(i, 1).length : 0; };
const value = (flag, dflt) => { const i = argv.indexOf(flag); return i >= 0 ? argv.splice(i, 2)[1] : dflt; };

if (take('--rank')) {
  const top = Number(value('--top', 32));
  const weight = new Map();
  for (const file of argv) {
    const rows = readFileSync(file, 'utf8').trim().split('\n').map((l) => l.trim().split(/\s+/).map(Number));
    const total = rows.reduce((s, r) => s + r[1], 0);
    for (const [w, c] of rows) weight.set(w, (weight.get(w) ?? 0) + c / total / argv.length);
  }
  const ranked = [...weight].sort((a, b) => b[1] - a[1] || a[0] - b[0]);
  let sum = 0;
  for (const [w, x] of ranked.slice(0, top)) {
    sum += x;
    console.log(`'${name(w)}', // ${(100 * x).toFixed(2)}%, cumulative ${(100 * sum).toFixed(2)}%`);
  }
  process.exit(0);
}

const out = value('-o', null);
const mode = take('--full') ? 'full' : take('--partial') ? 'partial' : (take('--hot'), 'hot');
const lines = [
  '// SPDX-License-Identifier: MIT',
  '// Copyright (c) 2026 Martin Leitner-Ankerl',
  `// Generated by lib/src/gen-dispatch.mjs --${mode}; do not edit.`,
  '// Included inside the dispatch switch of step() in mars.c.',
];
if (mode === 'hot') {
  const seen = new Set();
  for (const [i, text] of HOT.entries()) {
    const w = parse(text);
    if (seen.has(w)) throw new Error(`duplicate HOT entry '${text}'`);
    seen.add(w);
    if (i === 16) lines.push('#ifndef M42_DISPATCH_16');
    lines.push(`case ${w}: return EXEC(${w}); // ${text}`);
  }
  if (HOT.length > 16) lines.push('#endif');
} else if (mode === 'full') {
  for (let op = 0; op < OPS.length; op++) {
    for (let mod = 0; mod < MODS.length; mod++) {
      for (let am = 0; am < 8; am++) {
        for (let bm = 0; bm < 8; bm++) lines.push(`case ${word(op, mod, am, bm)}: return EXEC(${word(op, mod, am, bm)});`);
      }
    }
  }
} else {
  // The switch in mars.c is on the whole word; a nested switch on the op
  // byte and the B mode (an 11-bit key) leaves the A mode bits variable.
  lines.push('default: switch ((ins & 0xffu) | ((ins >> 3) & 0x700u)) {');
  for (let op = 0; op < OPS.length; op++) {
    for (let mod = 0; mod < MODS.length; mod++) {
      for (let bm = 0; bm < 8; bm++) {
        const w = word(op, mod, 0, bm);
        lines.push(`  case ${(w & 0xff) | (bm << 8)}: return EXEC((ins & 0x700u) | ${w});`);
      }
    }
  }
  lines.push('  }');
}
const text = lines.join('\n') + '\n';
if (out) writeFileSync(out, text);
else process.stdout.write(text);
